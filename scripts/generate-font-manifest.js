#!/usr/bin/env node
// Generates public/js/fontManifest.js by inspecting the real font files in
// public/fonts/ — never from memory, per docs/v2-spec.md's P3.1 section.
// Reads each font's actual OS/2.usWeightClass (static weights) or fvar
// variation axes (variable fonts), plus a Japanese-glyph-coverage probe
// (hiragana/katakana/a common kanji codepoint), and writes them keyed by
// the same ids as public/js/fonts.js's hand-authored FONT_CATALOG.
//
// Run with: node scripts/generate-font-manifest.js (or `npm run
// generate:font-manifest`) — no arguments, paths resolved relative to this
// file, same convention as scripts/generate-themes.js.
//
// fontkit is a devDependency used only by this script — nothing under
// public/ imports it. The generated output below has zero dependency on
// fontkit or Node at runtime; it's plain data.

const fs = require('fs');
const path = require('path');
const fontkit = require('fontkit');

const FONTS_DIR = path.join(__dirname, '..', 'public', 'fonts');
const OUT_FILE = path.join(__dirname, '..', 'public', 'js', 'fontManifest.js');

// Which real file(s) back each public/js/fonts.js FONT_CATALOG id. Kept
// here (not derived from a naming convention) because a font's shipped
// filename and its catalog id are related but not mechanically identical
// (e.g. instrument-serif ships a normal and an italic file, both feeding
// one manifest entry).
const CATALOG_FILES = {
  'schibsted-grotesk': ['schibsted-grotesk-400.woff2', 'schibsted-grotesk-500.woff2', 'schibsted-grotesk-600.woff2'],
  'zen-old-mincho': ['zen-old-mincho-600.woff2', 'zen-old-mincho-700.woff2'],
  inter: ['inter-variable.woff2'],
  'dm-sans': ['dm-sans-variable.woff2'],
  nunito: ['nunito-variable.woff2'],
  'space-grotesk': ['space-grotesk-variable.woff2'],
  'bebas-neue': ['bebas-neue-400.woff2'],
  'instrument-serif': ['instrument-serif-400.woff2', 'instrument-serif-400-italic.woff2'],
  'jetbrains-mono': ['jetbrains-mono-variable.woff2'],
  'noto-sans-jp': ['noto-sans-jp-japanese-400.woff2'],
  // Post-2.2.0 feedback: 3 new, stylistically distinct additions.
  fraunces: ['fraunces-variable.woff2'],
  fredoka: ['fredoka-variable.woff2'],
  'space-mono': ['space-mono-400.woff2', 'space-mono-700.woff2'],
  // system-default ships no file at all — zeroLoad in fonts.js.
};

// A representative probe, not exhaustive CJK-completeness: hiragana 'あ'
// (U+3042), katakana 'ア' (U+30A2), and a common kanji '日' (U+65E5). A
// font passes jpCoverage if it has glyphs for all three.
const JP_PROBE_CODEPOINTS = [0x3042, 0x30a2, 0x65e5];

function inspectFamily(files) {
  let weights = new Set();
  let variableAxes = null;
  let jpCoverage = true;

  for (const file of files) {
    const font = fontkit.openSync(path.join(FONTS_DIR, file));
    const axes = font.variationAxes && font.variationAxes.wght;
    if (axes) {
      variableAxes = { wght: [axes.min, axes.max] };
    } else {
      const weightClass = font['OS/2'] ? font['OS/2'].usWeightClass : null;
      if (weightClass) weights.add(weightClass);
    }
    for (const cp of JP_PROBE_CODEPOINTS) {
      if (!font.hasGlyphForCodePoint(cp)) jpCoverage = false;
    }
  }

  return {
    weights: variableAxes ? null : Array.from(weights).sort((a, b) => a - b),
    variableAxes,
    jpCoverage,
  };
}

function main() {
  const manifest = {};
  for (const [id, files] of Object.entries(CATALOG_FILES)) {
    manifest[id] = inspectFamily(files);
  }
  // system-default has no backing file to inspect — record it explicitly
  // rather than omitting it, so a manifest consumer never has to special-
  // case a missing key.
  manifest['system-default'] = { weights: null, variableAxes: null, jpCoverage: false };

  const body = Object.entries(manifest)
    .map(([id, data]) => `  '${id}': ${JSON.stringify(data)},`)
    .join('\n');

  const output = `// GENERATED by scripts/generate-font-manifest.js — do not hand-edit.
// Re-run: node scripts/generate-font-manifest.js (or npm run generate:font-manifest)
//
// One entry per public/js/fonts.js FONT_CATALOG id. weights is an array of
// static OS/2 weight classes actually present in the shipped file(s), or
// null for a variable font (use variableAxes instead). variableAxes.wght
// is [min, max] from the font's own fvar table, or null for a static
// font. jpCoverage is true only if the font has real glyphs for a
// hiragana, a katakana, and a common kanji probe codepoint — not full
// CJK completeness, a functional smoke check.
export const FONT_MANIFEST = {
${body}
};
`;

  fs.writeFileSync(OUT_FILE, output);
  console.log(`Wrote ${Object.keys(manifest).length} entries to ${OUT_FILE}`);
}

main();
